"""CHANGES-v0.2.md: what the corrected rerun changed relative to the v0.1 release.

Compares data/audit_v0.1.db (the database as it stood before the rerun) and the v0.1 release outputs (git tag
v0.1) with the current database and out/.
  python audit/changes.py
"""
import csv
import io
import json
import re
import sqlite3
import subprocess
from collections import Counter

import config as C
import paper_text as PT
import validation as V
import xref_llm as X

OLD_DB = C.DATA / "audit_v0.1.db"
TAG = "v0.1"


def git_show(path):
    r = subprocess.run(["git", "show", f"{TAG}:{path}"], capture_output=True, cwd=C.ROOT)
    return r.stdout.decode("utf-8-sig") if r.returncode == 0 else None


def status(con):
    con.row_factory = sqlite3.Row
    out = {r["item"]: dict(r) for r in con.execute("SELECT * FROM search_status")}
    con.row_factory = None
    return out


def shortlist_entries(text):
    return [re.sub(r"\s*·\s*\*\*validation\*\*", "", m.group(1)).strip()
            for m in re.finditer(r"^## \d+\. (.*)$", text or "", re.M)]


def old_paper_block(it):
    """The locating paper block as v0.1 built it: the OCR proof preferred whenever present."""
    it = dict(it)
    it["proof"], it["proof_latex"] = it.get("proof_latex") or it.get("proof"), None
    return X.paper_block(it)


def main():
    old, new = sqlite3.connect(OLD_DB), sqlite3.connect(C.DB)
    out = ["# Changes in v0.2", "",
           "What the corrected rerun changed relative to the v0.1 release (tag `v0.1`). Generated by "
           "`audit/changes.py`. The rerun used the same model and settings; prompts whose text was unchanged were "
           "answered from the v0.1 response cache, every other prompt was sampled fresh.", ""]

    # --- prompts affected by the paper-side truncation fix ---
    old.row_factory = new.row_factory = sqlite3.Row
    oi = {r["label"]: dict(r) for r in old.execute("SELECT * FROM paper_items")}
    ni = {r["label"]: dict(r) for r in new.execute("SELECT * FROM paper_items")}
    os_ = {r["label"]: dict(r) for r in old.execute("SELECT * FROM paper_steps")}
    ns_ = {r["label"]: dict(r) for r in new.execute("SELECT * FROM paper_steps")}
    old.row_factory = new.row_factory = None
    loc_changed = sorted(lab for lab in ni if X.paper_block(ni[lab]) != old_paper_block(oi[lab]))
    step_changed = sorted(lab for lab in ns_ if (os_.get(lab) or {}).get("statement_latex") != ns_[lab]["statement_latex"])
    old_pairs = [r[0] for r in old.execute("SELECT DISTINCT item FROM extract_pairs")]
    cmp_changed = sorted(i for i in old_pairs if i in oi and (oi[i]["proof_latex"] or oi[i]["proof"] or "")[:12000]
                         != PT.choose_proof(ni[i])[0][:20000])
    short = {lab: (len((oi[lab]["proof_latex"] or oi[lab]["proof"] or "")), len(PT.choose_proof(ni[lab])[0]))
             for lab in cmp_changed}
    out += ["## Prompts affected by the paper-text fix", "",
            f"- Locating prompts (paper block) changed for **{len(loc_changed)} of {len(ni)}** numbered results.",
            f"- Proof-step prompts changed for **{len(step_changed)} of {len(ns_)}** steps: "
            + ", ".join(step_changed) + ". In v0.1 these carried only the bare equation, because the proof text "
              "around them had been cut off at a page boundary.",
            f"- Comparison prompts: the paper text changed for **{len(cmp_changed)}** of the {len(old_pairs)} "
            "results and steps compared in v0.1 (characters of proof, v0.1 → v0.2: "
            + ", ".join(f"{k} {a:,} → {b:,}" for k, (a, b) in short.items()) + "). Every comparison prompt "
            "changed anyway, because the instruction about Lean section variables was corrected.", ""]

    # --- targets whose match changed ---
    so, sn = status(old), status(new)
    rows = []
    for item in sorted(set(so) | set(sn)):
        a, b = so.get(item, {}), sn.get(item, {})
        fa = {c["decl"]: c["agreement"] for c in json.loads(a.get("found_all") or "[]")}
        fb = {c["decl"]: c["agreement"] for c in json.loads(b.get("found_all") or "[]")}
        if (a.get("found_decl"), a.get("status")) != (b.get("found_decl"), b.get("status")) or set(fa) != set(fb):
            rows.append((item, a.get("status", "-"), (a.get("found_decl") or "-").split(".", 1)[-1],
                         b.get("status", "-"), (b.get("found_decl") or "-").split(".", 1)[-1],
                         len(set(fb) - set(fa)), len(set(fa) - set(fb))))
    out += ["## Targets whose match changed", "",
            f"{len(rows)} of {len(sn)} targets changed their top declaration, status, or set of agreed declarations.",
            "", "| Target | v0.1 | v0.1 declaration | v0.2 | v0.2 declaration | agreed decls added | removed |",
            "|---|---|---|---|---|--:|--:|"]
    out += [f"| {r[0]} | {r[1]} | `{r[2]}` | {r[3]} | `{r[4]}` | {r[5]} | {r[6]} |" for r in rows]
    out.append("")

    # --- agreement ---
    v1 = list(csv.DictReader(io.StringIO(git_show("out/differences.csv") or "")))
    v2 = list(csv.DictReader(open(C.OUT / "differences.csv", encoding="utf-8-sig")))
    c1 = Counter(r["agreement"] for r in v1)
    ov = Counter(r["overlapping_citations"] for r in v2)
    conf = Counter(r["agreement_csv"] or "not confirmed" for r in v2)
    adj = Counter(r["adjudicated_same"] for r in v2 if r["adjudicated_same"] != "")
    out += ["## Agreement", "",
            "v0.1 counted a difference as \"reported by all 3 samples\" when 3 samples cited overlapping Lean lines. "
            "v0.2 keeps that count as `overlapping_citations` and adds an adjudication pass: for every group with 2 "
            "or more samples, 3 further samples answer only whether the descriptions assert the same difference. "
            "`agreement` is reported only where all 3 said yes.", "",
            "| | v0.1 release | v0.2, overlapping citations | v0.2, confirmed by adjudication |", "|---|--:|--:|--:|",
            f"| grouped differences | {len(v1):,} | {len(v2):,} | {len(v2):,} |",
            f"| 3 of 3 | {c1['3']} | {ov['3']} | {conf['3']} |",
            f"| 2 of 3 | {c1['2']} | {ov['2']} | {conf['2']} |",
            f"| 1 of 3 | {c1['1']} | {ov['1']} | {conf['1']} |",
            f"| overlapping but not confirmed | - | - | {conf['not confirmed']} |", "",
            "Adjudication results over the groups with 2 or more samples: "
            + ", ".join(f"{k} of 3 said same: {adj[k]}" for k in sorted(adj, reverse=True)) + ".", "",
            "v0.1 and v0.2 groups are not matched one to one: the comparison was re-sampled, and v0.1's grouping "
            "also chained overlapping citations.", ""]

    # --- shortlist ---
    s1 = shortlist_entries(git_show("out/review_shortlist.md"))
    s2 = shortlist_entries(open(C.OUT / "review_shortlist.md", encoding="utf-8").read())
    added, removed = [e for e in s2 if e not in s1], [e for e in s1 if e not in s2]
    out += ["## Shortlist", "", f"v0.1: {len(s1)} entries; v0.2: {len(s2)} entries. Entries are (paper result, Lean "
            "declaration); a pair can appear more than once.", "",
            f"Added ({len(added)}):", ""] + [f"- {e}" for e in added] + [""] + \
           [f"Removed ({len(removed)}):", ""] + [f"- {e}" for e in removed] + [""]

    # --- retrospective recovery ---
    out += ["## Retrospective recovery of the two published discrepancies", "",
            "Both runs scored with v0.2's location-and-type check (a sample hits the target if it reported a "
            "difference of an allowed type whose Lean quote is found at the target lines).", "",
            "| Target | v0.1 samples | v0.1 control (pairs; windows) | v0.2 samples | v0.2 control (pairs; windows) |",
            "|---|--:|---|--:|---|"]
    for v in C.VALIDATION:
        a, b = V.check(old, v), V.check(new, v)
        ca, cb = a["control"], b["control"]
        out.append(f"| {v['item']} | {a['k']} of 3 | {ca['pairs_fired']} of {ca['pairs']}; {ca['window_rate']:.1%} | "
                   f"{b['k']} of 3 | {cb['pairs_fired']} of {cb['pairs']}; {cb['window_rate']:.1%} |")
    out.append("")
    (C.ROOT / "CHANGES-v0.2.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote CHANGES-v0.2.md")


if __name__ == "__main__":
    main()
